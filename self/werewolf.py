# شکل‌های مختلف حروف فارسی/عربی و فاصلهٔ مجازی را یکسان می‌کند.
_CHAR_TRANSLATION = str.maketrans({
    "ي": "ی", "ى": "ی", "ك": "ک", "ۀ": "ه", "ة": "ه", "ؤ": "و",
    "إ": "ا", "أ": "ا", "ٱ": "ا", "آ": "ا",
})
_DIACRITICS_RE = re.compile(r"[\u064b-\u065f\u0670\u06d6-\u06ed]")
_SPACE_RE = re.compile(r"[\s\u200c\u200dـ_-]+")


def normalize_name(value):
    """نام نقش را برای پشتیبانی از املاهای مختلف نرمال می‌کند."""
    value = (value or "").strip().lower().translate(_CHAR_TRANSLATION)
    value = _DIACRITICS_RE.sub("", value)
    return _SPACE_RE.sub(" ", value).strip()


def _build_alias_index():
    index = {}
    for key, role in ROLES.items():
        names = (key, role["name"], role["english"], *role["aliases"])
        for name in names:
            index[normalize_name(name)] = key
    return index


ALIASES = _build_alias_index()


def parse_training_command(text):
    """اگر متن دستور آموزش باشد، عبارت بعد از آن را برمی‌گرداند."""
    normalized = normalize_name(text)
    if normalized == "اموزش":
        return ""
    if normalized.startswith("اموزش "):
        # از نسخهٔ نرمال‌شده استفاده می‌کنیم تا «آموزش» و «اموزش» یکی باشند.
        return normalized[len("اموزش "):].strip()
    return None


def find_role(query):
    """نقش را با نام رسمی، انگلیسی یا نام مستعار پیدا می‌کند."""
    key = ALIASES.get(normalize_name(query))
    return ROLES.get(key) if key else None


def format_role(role):
    """توضیح کامل و آمادهٔ ارسال در تلگرام می‌سازد."""
    notes = "\n".join(f"• {note}" for note in role["notes"])
    return (
        f"{role['emoji']} آموزش نقش {role['name']} ({role['english']})\n\n"
        f"🏳️ تیم: {role['team']}\n"
        f"⏰ زمان قابلیت: {role['timing']}\n"
        f"🔢 تعداد استفاده: {role['uses']}\n"
        f"🎯 هدف: {role['goal']}\n\n"
        f"📖 قابلیت:\n{role['ability']}\n\n"
        f"📌 نکات مهم:\n{notes}\n\n"
        f"💡 پیشنهاد بازی:\n{role['strategy']}"
    )


